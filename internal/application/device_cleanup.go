// Retiring a format or a profile can also remove from each device what its
// formats delivered there (ADR 0060). The ownership ledgers say exactly what
// that is (ADR 0032, ADR 0040), so this file lists it for a screen and, when
// the operator asks, removes it before the retirement of ADR 0051.
//
// The act is all or nothing as far as a set of routers allows. Every surface
// must be reachable through a saved connection with a saved password before
// any device is contacted; every device is then asked, read-only, before any is
// changed; and the format or profile is retired only after every removal
// verified. A refusal at any point retires nothing.

var (
	// ErrDeviceCleanupUnavailable refuses a requested cleanup before any device
	// is contacted: some delivered objects have no saved connection with a
	// saved password through which they could be removed.
	ErrDeviceCleanupUnavailable = errors.New("delivered objects cannot be removed from every device")
	ErrDeviceCleanupComposition = errors.New("invalid device cleanup composition")
)

// Why a surface cannot be cleaned automatically. A screen states each one
// beside the surface it concerns.
const (
	// CleanupBlockedConnectionMissing: no saved connection of the format's
	// target reaches this surface (the same canonical address and, for static
	// routes, the same interface).
	CleanupBlockedConnectionMissing = "connection_missing"
	// CleanupBlockedLoginMissing: the matching saved connection holds no
	// saved password, or the password could not be read.
	CleanupBlockedLoginMissing = "credential_missing"
	// CleanupBlockedRemovalUnsupported: the format's target left the catalog,
	// has no deployer in this build, or its deployer cannot remove.
	CleanupBlockedRemovalUnsupported = "removal_unsupported"
)

// DeviceObjects is what one format's ownership ledger says Routevane delivered
// to one device surface. It names objects only: no credential, no device
// configuration.
type DeviceObjects struct {
	OutputID string `json:"output_id"`
	TargetID string `json:"target_id"`
	// Endpoint is the canonical device address the ledger is keyed by.
	Endpoint string `json:"endpoint"`
	// Interface is the device interface the objects were attached to.
	Interface string `json:"interface"`
	// Connection is the saved connection a cleanup would sign in with, absent
	// when none matches.
	Connection *DeviceObjectsConnection `json:"connection,omitempty"`
	// Cleanable says a cleanup can reach this surface; BlockedBy says why not.
	Cleanable bool   `json:"cleanable"`
	BlockedBy string `json:"blocked_by,omitempty"`
	// FQDNGroups names the groups this format owns there (Keenetic DNS).
	FQDNGroups []string `json:"fqdn_groups,omitempty"`
	// Routes counts this format's static-route claims there (Keenetic BAT).
	Routes *DeviceRouteCounts `json:"routes,omitempty"`
}

// DeviceObjectsConnection identifies the matching saved connection.
type DeviceObjectsConnection struct {
	ID               string `json:"id"`
	Name             string `json:"name"`
	CredentialStored bool   `json:"credential_stored"`
}

// DeviceRouteCounts splits a format's claimed static routes by what a cleanup
// would do with them. Claimed is the sum of the other three.
type DeviceRouteCounts struct {
	Claimed int `json:"claimed"`
	// Removable routes were created by Routevane and no other format claims
	// them: a cleanup removes them.
	Removable int `json:"removable"`
	// Shared routes stay because another format on the same surface still
	// claims them.
	Shared int `json:"shared"`
	// Preexisting routes stay because the router held them before Routevane
	// claimed them.
	Preexisting int `json:"preexisting"`
}

// DeliveredObjectIndex finds where one output's ledgers name objects. Only
// active ownership is listed: a retired route scope authorizes nothing.
type DeliveredObjectIndex interface {
	OutputFQDNEndpoints(context.Context, string) ([]string, error)
	OutputManagedRouteScopes(context.Context, string) ([]ManagedRouteScope, error)
}

// DeviceCleanupAttempt is the durable record of one removal from one device:
// which format, through which saved connection, at which surface, and the
// audited steps and outcome, like a deployment attempt. Its identity is
// generated by the server: a removal is convergent, so a repeated request
// finds nothing left rather than needing an operation it can replay.
type DeviceCleanupAttempt struct {
	ID          string                  `json:"attempt_id"`
	OutputID    string                  `json:"output_id"`
	DeviceID    string                  `json:"device_id"`
	Endpoint    string                  `json:"endpoint"`
	Status      DeploymentAttemptStatus `json:"status"`
	StartedAt   time.Time               `json:"started_at"`
	CompletedAt time.Time               `json:"completed_at,omitzero"`
	Result      DeployResult            `json:"result"`
	Error       string                  `json:"error,omitempty"`
}

// DeviceCleanupJournal records each removal attempt before its first device
// effect and completes it once. It is declared here, by its consumer.
type DeviceCleanupJournal interface {
	BeginDeviceCleanupAttempt(context.Context, DeviceCleanupAttempt) error
	CompleteDeviceCleanupAttempt(context.Context, DeviceCleanupAttempt) error
}

// CleanupPublication is what a cleanup needs from publication: the objects
// being retired, their targets, and the retirement itself.
type CleanupPublication interface {
	Profile(context.Context, string) (Profile, error)
	Output(context.Context, string) (Output, error)
	Outputs(context.Context, string) ([]Output, error)
	TargetDefinition(string) (domain.TargetDefinition, error)
	RemoveOutput(context.Context, string) (time.Time, error)
	DeleteProfile(context.Context, string) (time.Time, error)
}

// CleanupDevices is what a cleanup needs from the connection registry.
type CleanupDevices interface {
	DeviceCards(context.Context) ([]DeviceCard, error)
	DeviceCredential(context.Context, string) (string, error)
}

type DeviceCleanupConfig struct {
	Publication   CleanupPublication
	Devices       CleanupDevices
	Deployers     DeployerRegistry
	Backups       BackupStore
	ManagedRoutes ManagedRouteRepository
	ManagedFQDN   ManagedFQDNRepository
	Delivered     DeliveredObjectIndex
	Journal       DeviceCleanupJournal
	Clock         Clock
	Entropy       io.Reader
}

// DeviceCleanupService lists and removes what retired formats delivered. It
// owns no transport and no ledger: the deployers and the ownership
// repositories do, exactly as for a send.
type DeviceCleanupService struct {
	config DeviceCleanupConfig
}

func NewDeviceCleanupService(config DeviceCleanupConfig) (*DeviceCleanupService, error) {
	if config.Publication == nil || config.Devices == nil || len(config.Deployers) == 0 || config.Backups == nil ||
		config.ManagedRoutes == nil || config.ManagedFQDN == nil || config.Delivered == nil || config.Journal == nil ||
		config.Clock == nil || config.Entropy == nil {
		return nil, ErrDeviceCleanupComposition
	}
	return &DeviceCleanupService{config: config}, nil
}

// Retirement is a completed retirement and the removals that preceded it.
type Retirement struct {
	RetiredAt time.Time
	Cleanups  []DeviceCleanupAttempt
}

// DeviceCleanupRefusal is a cleanup that stopped a retirement. Nothing was
// retired. Blocked lists the surfaces no saved connection can clean when the
// refusal came before any device was contacted. Otherwise Objects is the
// surface it stopped at and Step the step; Cleanups holds every attempt this
// request made, the failed one last. Surfaces cleaned before the failure stay
// clean, and their ledger rows are already gone.
type DeviceCleanupRefusal struct {
	Blocked  []DeviceObjects
	Objects  *DeviceObjects
	Step     string
	Cleanups []DeviceCleanupAttempt
	Err      error
}

func (e *DeviceCleanupRefusal) Error() string { return "device cleanup refused: " + e.Err.Error() }
func (e *DeviceCleanupRefusal) Unwrap() error { return e.Err }

// Code is the stable failure code a screen shows.
func (e *DeviceCleanupRefusal) Code() string { return DeviceCleanupFailureCode(e.Err) }

// DeviceCleanupFailureCode classifies a refused cleanup with the codes a send
// uses, so a device's reason reads the same in both places. A removal has no
// artifact to apply, so its unclassified failure is device_cleanup_failed
// rather than deploy_failed.
func DeviceCleanupFailureCode(err error) string {
	switch {
	case err == nil:
		return ""
	case errors.Is(err, ErrDeviceCleanupUnavailable), errors.Is(err, ErrRemovalUnsupported):
		return "device_cleanup_unavailable"
	}
	if code := DeploymentFailureCode(err); code != "deploy_failed" {
		return code
	}
	return "device_cleanup_failed"
}

// OutputDeviceObjects lists what one live format delivered, by surface.
func (s *DeviceCleanupService) OutputDeviceObjects(ctx context.Context, outputID string) ([]DeviceObjects, error) {
	output, err := s.config.Publication.Output(ctx, outputID)
	if err != nil {
		return nil, err
	}
	entries, err := s.entries(ctx, []Output{output})
	return objectsOf(entries), err
}

// ProfileDeviceObjects lists what every live format of one profile delivered,
// archived profiles included: deletion is the step after archival.
func (s *DeviceCleanupService) ProfileDeviceObjects(ctx context.Context, profileID string) ([]DeviceObjects, error) {
	if _, err := s.config.Publication.Profile(ctx, profileID); err != nil {
		return nil, err
	}
	outputs, err := s.config.Publication.Outputs(ctx, profileID)
	if err != nil {
		return nil, err
	}
	entries, err := s.entries(ctx, outputs)
	return objectsOf(entries), err
}

// RemoveOutput removes what one format delivered from every device, then
// retires the format. The caller holds the delivery gate.
func (s *DeviceCleanupService) RemoveOutput(ctx context.Context, outputID string) (Retirement, error) {
	output, err := s.config.Publication.Output(ctx, outputID)
	if err != nil {
		return Retirement{}, err
	}
	profile, err := s.config.Publication.Profile(ctx, output.ProfileID)
	if err != nil {
		return Retirement{}, err
	}
	// The refusals the retirement itself would answer come before any device
	// is touched.
	if err := profile.writable(); err != nil {
		return Retirement{}, err
	}
	cleanups, err := s.clean(ctx, []Output{output})
	if err != nil {
		return Retirement{Cleanups: cleanups}, err
	}
	retiredAt, err := s.config.Publication.RemoveOutput(ctx, output.ID)
	return Retirement{RetiredAt: retiredAt, Cleanups: cleanups}, err
}

// DeleteProfile removes what every format of an archived profile delivered,
// then deletes the profile. The caller holds the delivery gate.
func (s *DeviceCleanupService) DeleteProfile(ctx context.Context, profileID string) (Retirement, error) {
	profile, err := s.config.Publication.Profile(ctx, profileID)
	if err != nil {
		return Retirement{}, err
	}
	if !profile.Archived() {
		return Retirement{}, ErrProfileNotArchived
	}
	outputs, err := s.config.Publication.Outputs(ctx, profile.ID)
	if err != nil {
		return Retirement{}, err
	}
	cleanups, err := s.clean(ctx, outputs)
	if err != nil {
		return Retirement{Cleanups: cleanups}, err
	}
	retiredAt, err := s.config.Publication.DeleteProfile(ctx, profile.ID)
	return Retirement{RetiredAt: retiredAt, Cleanups: cleanups}, err
}

// cleanupEntry is one surface with what a removal needs to reach it.
type cleanupEntry struct {
	objects         DeviceObjects
	target          domain.TargetDefinition
	device          Device
	needsCredential bool
}

func objectsOf(entries []cleanupEntry) []DeviceObjects {
	objects := make([]DeviceObjects, 0, len(entries))
	for _, entry := range entries {
		objects = append(objects, entry.objects)
	}
	return objects
}

// clean removes every surface's objects or refuses. It never retires.
func (s *DeviceCleanupService) clean(ctx context.Context, outputs []Output) ([]DeviceCleanupAttempt, error) {
	entries, err := s.entries(ctx, outputs)
	if err != nil {
		return nil, err
	}
	blocked := make([]DeviceObjects, 0)
	for _, entry := range entries {
		if !entry.objects.Cleanable {
			blocked = append(blocked, entry.objects)
		}
	}
	if len(blocked) > 0 {
		return nil, &DeviceCleanupRefusal{Blocked: blocked, Err: ErrDeviceCleanupUnavailable}
	}
	requests := make([]RemovalRequest, len(entries))
	for index, entry := range entries {
		connection := Connection{URL: entry.device.Address, Username: entry.device.Account, Interface: entry.device.Interface}
		if entry.needsCredential {
			secret, err := s.config.Devices.DeviceCredential(ctx, entry.device.ID)
			if err != nil || secret == "" {
				objects := entry.objects
				objects.Cleanable, objects.BlockedBy = false, CleanupBlockedLoginMissing
				return nil, &DeviceCleanupRefusal{Blocked: []DeviceObjects{objects}, Err: ErrDeviceCleanupUnavailable}
			}
			connection.Password = secret
		}
		requests[index] = RemovalRequest{
			Target: entry.target, Connection: connection, OutputID: entry.objects.OutputID,
			ManagedRoutes: s.config.ManagedRoutes, ManagedFQDN: s.config.ManagedFQDN,
		}
	}
	// Every device is asked before any is changed, so a refused password or an
	// unreachable second router stops the act while the first is untouched.
	for index := range requests {
		if err := PreviewRemoval(ctx, requests[index], s.config.Deployers, s.config.Clock); err != nil {
			objects := entries[index].objects
			return nil, &DeviceCleanupRefusal{Objects: &objects, Step: RefusalStep(err), Err: err}
		}
	}
	attempts := make([]DeviceCleanupAttempt, 0, len(requests))
	for index := range requests {
		attempt, err := s.attempt(ctx, entries[index], requests[index])
		if attempt.ID != "" {
			attempts = append(attempts, attempt)
		}
		if err != nil {
			objects := entries[index].objects
			step := attempt.Result.FailedStep()
			if step == "" {
				step = RefusalStep(err)
			}
			return attempts, &DeviceCleanupRefusal{Objects: &objects, Step: step, Cleanups: attempts, Err: err}
		}
	}
	return attempts, nil
}

// attempt records one removal before it reaches the device and completes the
// record afterwards, with the same cancellation-independent budget a
// deployment attempt uses.
func (s *DeviceCleanupService) attempt(ctx context.Context, entry cleanupEntry, request RemovalRequest) (DeviceCleanupAttempt, error) {
	id, err := randomHex(s.config.Entropy, 16)
	if err != nil {
		return DeviceCleanupAttempt{}, fmt.Errorf("generate device cleanup attempt identity: %w", err)
	}
	proposed := DeviceCleanupAttempt{
		ID: id, OutputID: entry.objects.OutputID, DeviceID: entry.device.ID, Endpoint: entry.objects.Endpoint,
		Status: DeploymentAttemptPending, StartedAt: s.config.Clock.Now().UTC(),
	}
	if err := s.config.Journal.BeginDeviceCleanupAttempt(ctx, proposed); err != nil {
		return DeviceCleanupAttempt{}, fmt.Errorf("begin device cleanup attempt %q: %w", id, err)
	}
	result, removeErr := RemoveFromDevice(ctx, request, s.config.Deployers, s.config.Backups, s.config.Clock)
	completed := proposed
	completed.Result = result
	completed.CompletedAt = s.config.Clock.Now().UTC()
	completed.Error = DeviceCleanupFailureCode(removeErr)
	completed.Status = DeploymentAttemptSucceeded
	if removeErr != nil {
		completed.Status = DeploymentAttemptFailed
	}
	persistCtx, cancel := context.WithTimeout(context.WithoutCancel(ctx), deploymentAttemptRecordBudget)
	defer cancel()
	if err := s.config.Journal.CompleteDeviceCleanupAttempt(persistCtx, completed); err != nil {
		// The device and its ledger already agree; only the record is
		// missing. The act stops here, and a repeated request finds this
		// surface empty.
		return completed, errors.Join(removeErr, fmt.Errorf("record device cleanup attempt %q: %w", id, err))
	}
	return completed, removeErr
}

// entries lists every surface the outputs' ledgers name, in output order and
// then by surface, with the saved connection that can reach each.
func (s *DeviceCleanupService) entries(ctx context.Context, outputs []Output) ([]cleanupEntry, error) {
	entries := make([]cleanupEntry, 0)
	for _, output := range outputs {
		endpoints, err := s.config.Delivered.OutputFQDNEndpoints(ctx, output.ID)
		if err != nil {
			return nil, err
		}
		for _, endpoint := range endpoints {
			owned, err := s.config.ManagedFQDN.ManagedFQDNOwnership(ctx, endpoint, output.ID)
			if err != nil {
				return nil, err
			}
			if len(owned.Groups) == 0 {
				continue
			}
			names := make([]string, 0, len(owned.Groups))
			for _, group := range owned.Groups {
				names = append(names, group.Name)
			}
			slices.Sort(names)
			entries = append(entries, cleanupEntry{objects: DeviceObjects{
				OutputID: output.ID, TargetID: output.TargetID, Endpoint: endpoint,
				Interface: owned.Groups[0].Interface, FQDNGroups: names,
			}})
		}
		scopes, err := s.config.Delivered.OutputManagedRouteScopes(ctx, output.ID)
		if err != nil {
			return nil, err
		}
		for _, scope := range scopes {
			owned, err := s.config.ManagedRoutes.ManagedRouteOwnership(ctx, scope)
			if err != nil {
				return nil, err
			}
			counts := routeCounts(owned, output.ID)
			if counts.Claimed == 0 {
				continue
			}
			entries = append(entries, cleanupEntry{objects: DeviceObjects{
				OutputID: output.ID, TargetID: output.TargetID, Endpoint: scope.Endpoint,
				Interface: scope.Interface, Routes: &counts,
			}})
		}
	}
	if len(entries) == 0 {
		return entries, nil
	}
	devices, err := s.config.Devices.DeviceCards(ctx)
	if err != nil {
		return nil, err
	}
	bound := make(map[string]string, len(outputs))
	for _, output := range outputs {
		bound[output.ID] = output.DeviceID
	}
	for index := range entries {
		s.match(&entries[index], devices, bound[entries[index].objects.OutputID])
	}
	return entries, nil
}

// match finds the saved connection a cleanup of one surface signs in with.
// A connection matches when its own deployer canonicalizes it to the ledger's
// surface: the same target and address, and for static routes the same
// interface. FQDN groups are device-wide (ADR 0040), so any interface of the
// matching address serves. Among several, one that can sign in (a saved
// password, when the deployer needs one) comes first, then the format's bound
// connection, then the oldest.
func (s *DeviceCleanupService) match(entry *cleanupEntry, devices []DeviceCard, boundDeviceID string) {
	entry.objects.Cleanable, entry.objects.BlockedBy = false, CleanupBlockedRemovalUnsupported
	target, err := s.config.Publication.TargetDefinition(entry.objects.TargetID)
	if err != nil {
		return
	}
	deployer, registered := s.config.Deployers[target.RendererID]
	if !registered || deployer == nil {
		return
	}
	fqdnOwner, ownsFQDN := deployer.(ManagedFQDNDeployer)
	_, removes := deployer.(ManagedFQDNRemover)
	routeOwner, ownsRoutes := deployer.(ManagedRouteDeployer)
	var surface func(Connection) bool
	switch {
	case entry.objects.FQDNGroups != nil && ownsFQDN && removes:
		surface = func(connection Connection) bool {
			endpoint, err := fqdnOwner.FQDNEndpoint(connection)
			return err == nil && endpoint == entry.objects.Endpoint
		}
	case entry.objects.Routes != nil && ownsRoutes:
		want := ManagedRouteScope{Endpoint: entry.objects.Endpoint, TargetID: target.ID, Interface: entry.objects.Interface}
		surface = func(connection Connection) bool {
			scope, err := routeOwner.ManagedRouteScope(target, connection)
			return err == nil && scope == want
		}
	default:
		return
	}
	entry.target = target
	entry.needsCredential = deployer.Requirements().NeedsCredential
	candidates := make([]DeviceCard, 0, 1)
	for _, device := range devices {
		if device.TargetID == target.ID && surface(Connection{URL: device.Address, Username: device.Account, Interface: device.Interface}) {
			candidates = append(candidates, device)
		}
	}
	if len(candidates) == 0 {
		entry.objects.BlockedBy = CleanupBlockedConnectionMissing
		return
	}
	// One that can sign in comes first: a saved password, or none needed.
	rank := func(device DeviceCard) int {
		score := 0
		if entry.needsCredential && !device.CredentialStored {
			score += 2
		}
		if device.ID != boundDeviceID {
			score++
		}
		return score
	}
	chosen := slices.MinFunc(candidates, func(a, b DeviceCard) int {
		return cmp.Or(cmp.Compare(rank(a), rank(b)), a.CreatedAt.Compare(b.CreatedAt), cmp.Compare(a.ID, b.ID))
	})
	entry.device = chosen.Device
	entry.objects.Connection = &DeviceObjectsConnection{ID: chosen.ID, Name: chosen.Name, CredentialStored: chosen.CredentialStored}
	if entry.needsCredential && !chosen.CredentialStored {
		entry.objects.BlockedBy = CleanupBlockedLoginMissing
		return
	}
	entry.objects.Cleanable, entry.objects.BlockedBy = true, ""
}

// routeCounts splits one output's claims on one scope by what a removal would
// do with each, from the ledger alone.
func routeCounts(owned ManagedRouteOwnership, outputID string) DeviceRouteCounts {
	created := make(map[string]bool, len(owned.Routes))
	for _, route := range owned.Routes {
		created[route.Prefix.String()] = route.CreatedByRoutevane
	}
	others := make(map[string]bool, len(owned.Claims))
	for _, claim := range owned.Claims {
		if claim.OutputID != outputID {
			others[claim.Prefix.String()] = true
		}
	}
	var counts DeviceRouteCounts
	for _, claim := range owned.Claims {
		if claim.OutputID != outputID {
			continue
		}
		prefix := claim.Prefix.String()
		counts.Claimed++
		switch {
		case !created[prefix]:
			counts.Preexisting++
		case others[prefix]:
			counts.Shared++
		default:
			counts.Removable++
		}
	}
	return counts
}
